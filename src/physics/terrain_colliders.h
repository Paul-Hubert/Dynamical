#ifndef DY_TERRAIN_COLLIDERS_H
#define DY_TERRAIN_COLLIDERS_H

#include "physics_world.h"

#include <Jolt/Physics/Collision/Shape/Shape.h>

#include <entt/entt.hpp>
#include <glm/glm.hpp>

#include <atomic>
#include <memory>
#include <unordered_map>
#include <vector>

#include "logic/terrain/chunk.h"

namespace dy {

class MarchingCubes;
class TerrainGenerator;

struct Bounds {
    glm::vec3 min;
    glm::vec3 max;
};

// Bodies that are no RigidBody component and need the terrain under them (a ragdoll's segments): world context
// variable, read by WorldTerrain
struct TerrainUsers {
    std::vector<JPH::BodyID> bodies;
};

// Static Jolt mesh colliders for the marching cubes terrain, built on the CPU only where bodies are or are heading.
//
// The world is cut in fixed cells of cell_cubes^3 marching cubes. Cells overlapping a body's swept bounds this
// frame are built (in parallel, in a fixed order) before the physics step; cells on the predicted path are
// prefetched on the taskflow executor. Densities come from the chunk volume when it is loaded, else straight
// from the TerrainGenerator, so collision works without the renderer or chunk streaming (headless simulation).
// Without a tf::Executor context variable (worlds, which already run in parallel) the required cells are built
// inline, in the same order, and prefetching is skipped.
class TerrainColliders {
public:
    static constexpr int cell_cubes = 16;
    static constexpr float cell_size = (float) (cell_cubes * chunk::cube_size);
    static constexpr double eviction_delay = 5.0; // seconds of simulation without a body nearby

    TerrainColliders(entt::registry& reg, PhysicsWorld& world);
    ~TerrainColliders();

    // required : bodies will touch these this frame, built synchronously. prefetch : built in the background.
    void update(const std::vector<Bounds>& required, const std::vector<Bounds>& prefetch, double time);

    // The cells overlapping bounds, built now (spawning on the ground)
    void require(const Bounds& bounds, double time) { update({ bounds }, {}, time); }

    // The generator's heightfield part of the surface (overhangs move the real surface by up to its overhang amplitude)
    float surfaceHeight(float x, float z) const;
    float overhangAmplitude() const;

    void clear();

    uint32_t activeCells() const;
    uint32_t triangles() const { return triangle_count; }

private:
    struct Job {
        glm::ivec3 cell;
        std::vector<float> samples;     // filled on the main thread from a loaded chunk, else generated by the job
        bool has_samples = false;
        bool empty = false;
        JPH::ShapeRefC shape;
        uint32_t triangles = 0;
        std::atomic<bool> done = false;
    };

    enum class State { Building, Built, Active, Empty };

    struct Cell {
        State state = State::Building;
        std::shared_ptr<Job> job;
        JPH::BodyID body;
        uint32_t triangles = 0;
        double last_used = 0.;
    };

    void cellsOverlapping(const Bounds& bounds, std::vector<glm::ivec3>& out) const;
    std::shared_ptr<Job> makeJob(glm::ivec3 cell);
    static void run(Job& job, const MarchingCubes& mc, const TerrainGenerator& generator);
    void activate(glm::ivec3 position, Cell& cell);

    entt::registry& reg;
    PhysicsWorld& world;
    std::shared_ptr<MarchingCubes> marching_cubes;
    std::shared_ptr<TerrainGenerator> generator;

    std::unordered_map<glm::ivec3, Cell, IVec3Hash> cells;
    uint32_t triangle_count = 0;
};

}

#endif
