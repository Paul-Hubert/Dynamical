#!/usr/bin/env python3
"""Generates the component pages, the indexes and the scene usage of docs/reference.

    python tools/gen_reference_docs.py            # write
    python tools/gen_reference_docs.py --check    # report gaps, exit 1 if any, write nothing

Inputs: docs/reference/data/*.json (written by hand with the system pages, schema in
docs/reference/README.md), the system pages docs/reference/systems/*.md, the registered systems
(registerSystem("...") in src/), the scenes (resources/scenes/**/*.json) and tools/docs_scan.py.
"""
import argparse, glob, json, os, re, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = os.path.join(ROOT, "docs", "reference")
sys.path.insert(0, os.path.join(ROOT, "tools"))
import docs_scan  # noqa: E402

GENERATED = "<!-- generated by tools/gen_reference_docs.py: do not edit, edit docs/reference/data/*.json -->"


def rel(path):
    return os.path.relpath(path, ROOT).replace("\\", "/")


def load_data():
    systems, components, errors = [], {}, []
    for f in sorted(glob.glob(os.path.join(REF, "data", "*.json"))):
        group = os.path.splitext(os.path.basename(f))[0]
        try:
            d = json.load(open(f, encoding="utf-8"))
        except json.JSONDecodeError as e:
            errors.append(f"{rel(f)}: {e}")
            continue
        for s in d.get("systems", []):
            s["group"] = group
            systems.append(s)
        for c in d.get("components", []):
            c["group"] = group
            if c["name"] in components:
                errors.append(f"component {c['name']} described in {components[c['name']]['group']} and {group}")
                continue
            components[c["name"]] = c
    return systems, components, errors


def page_of(s):
    """File name (in systems/) of a system entry."""
    if s.get("page"):
        return os.path.basename(s["page"])
    name, kind = s["name"], s.get("kind", "system")
    cands = [name]
    if kind == "pass":
        cands = [name if name.startswith("pass-") else "pass-" + name, name]
    elif kind == "service":
        cands = [name if name.startswith("service-") else "service-" + name, "service-" + s.get("class", name), name]
    for c in cands:
        if os.path.exists(os.path.join(REF, "systems", c + ".md")):
            return c + ".md"
    return cands[0] + ".md"


def registered_systems():
    out = {}
    for f in glob.glob(os.path.join(ROOT, "src", "**", "*.cpp"), recursive=True):
        text = open(f, encoding="utf-8", errors="replace").read()
        for m in re.finditer(r'registerSystem\("([^"]+)"', text):
            out[m.group(1)] = rel(f)
    return out


def scene_usage(names):
    """name -> sorted list of (scene file, lane)."""
    use = defaultdict(set)
    for f in sorted(glob.glob(os.path.join(ROOT, "resources", "scenes", "**", "*.json"), recursive=True)):
        try:
            d = json.load(open(f, encoding="utf-8"))
        except Exception:
            continue
        scene = os.path.relpath(f, os.path.join(ROOT, "resources", "scenes")).replace("\\", "/")

        def entry(e, lane):
            n = e if isinstance(e, str) else e.get("name") if isinstance(e, dict) else None
            if not isinstance(n, str):
                return
            base, _, phase = n.partition("@")
            if isinstance(e, dict) and e.get("phase"):
                phase = e["phase"]
            if base in names:
                use[base].add((scene, lane + ("@" + phase if phase else "")))

        def walk(node, path):
            if isinstance(node, dict):
                for k, v in node.items():
                    if k in ("pre", "post") and isinstance(v, list) and path and path[-1] == "host":
                        for e in v: entry(e, "host." + k)
                    elif k == "fixed" and isinstance(v, list):
                        for e in v: entry(e, "fixed")
                    elif k in ("replace", "add", "insert", "append") and isinstance(v, (list, dict)):
                        items = v if isinstance(v, list) else list(v.values())
                        for e in items: entry(e, "fixed")
                        walk(v, path + [k])
                    else:
                        walk(v, path + [k])
            elif isinstance(node, list):
                for v in node:
                    walk(v, path)
        walk(d, [])
    return {k: sorted(v) for k, v in use.items()}


def md_cell(x):
    return str(x if x is not None else "").replace("|", "\\|").replace("\n", " ")


def component_page(c, users, systems_by_page):
    name = c["name"]
    L = [GENERATED, "", f"# {name}", ""]
    meta = [f"Kind: {c.get('kind', 'component')}"]
    if c.get("file"):
        meta.append(f"Defined in [`{c['file']}`](../../../{c['file']})")
    if c.get("json"):
        meta.append(f"Scene / prefab name: `{c['json']}`")
    meta.append(f"Described in `data/{c['group']}.json`")
    L += [" · ".join(meta), "", c.get("summary", ""), ""]
    if c.get("fields"):
        L += ["## Fields", "", "| Field | Type | Meaning |", "|---|---|---|"]
        for f in c["fields"]:
            L.append(f"| `{md_cell(f.get('name'))}` | `{md_cell(f.get('type'))}` | {md_cell(f.get('desc'))} |")
        L.append("")
    if c.get("notes"):
        L += ["## Notes", "", c["notes"], ""]
    L += access_tables(name, users, systems_by_page)
    return "\n".join(L).rstrip() + "\n"


def access_tables(name, users, systems_by_page):
    L = []
    if not users:
        return ["## Systems that touch it", "", "None of the documented systems, passes or services.", ""]
    readers = sorted({u[0]["name"] for u in users if "read" in u[1]["access"] and "write" not in u[1]["access"]})
    writers = sorted({u[0]["name"] for u in users if "write" in u[1]["access"]})
    creators = sorted({u[0]["name"] for u in users if "create" in u[1]["access"]})
    destroyers = sorted({u[0]["name"] for u in users if "destroy" in u[1]["access"]})
    L += ["## Systems that touch it", ""]
    L.append(f"Read only by: {', '.join(readers) or '—'}. Written by: {', '.join(writers) or '—'}. "
             f"Created by: {', '.join(creators) or '—'}. Destroyed by: {', '.join(destroyers) or '—'}.")
    L += ["", "| System | Kind | Scope | Access | Where | What it does with it |", "|---|---|---|---|---|---|"]
    for s, a in sorted(users, key=lambda u: (u[0].get("kind", "system") != "system", u[0]["name"])):
        L.append(f"| [{s['name']}](../systems/{page_of(s)}) | {s.get('kind', 'system')} | {md_cell(s.get('scope', ''))} | "
                 f"**{md_cell(a['access'])}** | {md_cell(a.get('where', ''))} | {md_cell(a.get('effect', ''))} |")
    L += ["", "## Side effects of those systems", ""]
    seen = set()
    for s, _ in sorted(users, key=lambda u: u[0]["name"]):
        if s["name"] in seen:
            continue
        seen.add(s["name"])
        effects = s.get("side_effects") or []
        L.append(f"- **[{s['name']}](../systems/{page_of(s)})**" + ("" if effects else ": none beyond its components."))
        for e in effects:
            L.append(f"  - {e}")
    L.append("")
    return L


def fill_scene_usage(page_path, usage, write):
    if not os.path.exists(page_path):
        return False
    text = open(page_path, encoding="utf-8").read()
    m = re.search(r"^## Used in scenes[^\n]*\n", text, re.M)
    if not m:
        return False
    nxt = re.search(r"^## ", text[m.end():], re.M)
    end = m.end() + nxt.start() if nxt else len(text)
    if usage:
        body = "\n".join(f"- [`{f}`](../../../resources/scenes/{f}): `{lane}`" for f, lane in usage)
    else:
        body = "No scene lists it."
    new = text[:m.end()] + "\n<!-- generated -->\n" + body + "\n\n" + text[end:].lstrip("\n")
    if new != text and write:
        open(page_path, "w", encoding="utf-8", newline="\n").write(new)
    return new != text


def first_line(path):
    try:
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if line and not line.startswith(("#", "<!--", "`", "|", "-")):
                return line[:200]
    except OSError:
        pass
    return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    systems, components, errors = load_data()
    registered = registered_systems()
    systems_by_page = {page_of(s): s for s in systems}

    users = defaultdict(list)
    for s in systems:
        for acc in s.get("access", []):
            users[acc["name"]].append((s, acc))

    problems = list(errors)
    documented = {s["name"] for s in systems if s.get("kind", "system") == "system"}
    for n, f in sorted(registered.items()):
        if n not in documented:
            problems.append(f"registered system {n} ({f}) has no entry in data/*.json")
        if not os.path.exists(os.path.join(REF, "systems", n + ".md")):
            problems.append(f"registered system {n} ({f}) has no page systems/{n}.md")
    for s in systems:
        if not os.path.exists(os.path.join(REF, "systems", page_of(s))):
            problems.append(f"{s['group']}: {s['name']} has no page systems/{page_of(s)}")
    for n in sorted(users):
        if n not in components:
            problems.append(f"{n} is touched by {', '.join(sorted({u[0]['name'] for u in users[n]}))} but no data file describes it")

    # static scan: what the code of a system's class touches that its table does not name
    hits = []
    for d, _, files in os.walk(os.path.join(ROOT, "src")):
        if "mlagents" + os.sep + "proto" in d:
            continue
        for fn in files:
            if fn.endswith((".h", ".cpp")):
                hits += docs_scan.scan_file(os.path.join(d, fn))
    by_class = defaultdict(set)
    for h in hits:
        if h["scope"] and h["type"] != "<entity>":
            cls = h["scope"].split("::")[0]
            t = re.sub(r"^(std::shared_ptr|std::unique_ptr|ThreadSafe)<(.*)>$", r"\2", h["type"])
            by_class[cls].add(t.split("::")[-1] if "::" in t and not t.startswith("entt") else t)
    named_by_class = defaultdict(set)   # a class registered under several names (modes): the union of their tables
    for s in systems:
        for x in s.get("access", []):
            named_by_class[s.get("class")] |= {x["name"], x["name"].split("_")[-1]}
    for s in systems:
        cls = s.get("class")
        if not cls or cls not in by_class:
            continue
        named = named_by_class[cls]
        missing = sorted(t for t in by_class[cls] if t not in named and not t.startswith(("entt", "std")))
        if missing:
            problems.append(f"scan: {cls} ({s['name']}) touches {', '.join(missing)} not in its table")

    if a.check:
        for p in problems:
            print(p)
        print(f"{len(problems)} problem(s); {len(systems)} systems/passes/services, {len(components)} components, "
              f"{len(registered)} registered systems")
        sys.exit(1 if problems else 0)

    # component pages
    comp_dir = os.path.join(REF, "components")
    os.makedirs(comp_dir, exist_ok=True)
    for f in glob.glob(os.path.join(comp_dir, "*.md")):
        if open(f, encoding="utf-8").read().startswith(GENERATED):
            os.remove(f)
    names = sorted(set(components) | set(users))
    for n in names:
        c = components.get(n) or {"name": n, "kind": next((u[1].get("kind") for u in users[n]), "component"),
                                   "group": "?", "summary": "_Not described in any data file yet._"}
        open(os.path.join(comp_dir, n + ".md"), "w", encoding="utf-8", newline="\n").write(
            component_page(c, users.get(n, []), systems_by_page))

    # scene usage of the system pages
    usage = scene_usage(set(registered))
    for s in systems:
        if s.get("kind", "system") == "system":
            fill_scene_usage(os.path.join(REF, "systems", page_of(s)), usage.get(s["name"], []), True)

    # indexes
    L = [GENERATED, "", "# Systems", "", "Registered systems (the names scenes use), render passes and the renderer / game "
         "objects that touch the registry. Conventions in [../README.md](../README.md).", ""]
    for kind, title in (("system", "Registered systems"), ("pass", "Render passes"), ("service", "Services")):
        rows = sorted((s for s in systems if s.get("kind", "system") == kind), key=lambda s: s["name"].lower())
        if not rows:
            continue
        L += [f"## {title}", "", "| Name | Scope | Source | Scenes | Summary |", "|---|---|---|---|---|"]
        for s in rows:
            src = s.get("file", "")
            L.append(f"| [{s['name']}]({page_of(s)}) | {md_cell(s.get('scope', ''))} | "
                     f"[`{os.path.basename(src)}`](../../../{src}) | {len(usage.get(s['name'], [])) or ''} | {md_cell(s.get('summary', ''))} |")
        L.append("")
    open(os.path.join(REF, "systems", "index.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L))

    L = [GENERATED, "", "# Components and context variables", "",
         "Every page lists the systems that touch it, how (read / write / readwrite, create / destroy) and their side effects.", "",
         "| Name | Kind | Defined in | Readers | Writers | Summary |", "|---|---|---|---|---|---|"]
    for n in names:
        c = components.get(n, {})
        us = users.get(n, [])
        r = len({u[0]["name"] for u in us if "write" not in u[1]["access"]})
        w = len({u[0]["name"] for u in us if "write" in u[1]["access"]})
        f = c.get("file", "")
        L.append(f"| [{n}]({n}.md) | {c.get('kind', '?')} | {('`' + f + '`') if f else ''} | {r} | {w} | {md_cell(c.get('summary', ''))} |")
    open(os.path.join(comp_dir, "index.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")

    L = [GENERATED, "", "# Folders", "", "One page per folder of `src/`.", "", "| Folder | Summary |", "|---|---|"]
    for f in sorted(glob.glob(os.path.join(REF, "folders", "*.md"))):
        b = os.path.basename(f)
        if b == "index.md":
            continue
        L.append(f"| [{b[:-3].replace('-', '/')}]({b}) | {md_cell(first_line(f))} |")
    open(os.path.join(REF, "folders", "index.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")

    print(f"{len(names)} component pages, {len(systems)} systems/passes/services, {len(problems)} problem(s) "
          f"(--check lists them)")


if __name__ == "__main__":
    main()
